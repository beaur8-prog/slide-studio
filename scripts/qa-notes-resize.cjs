'use strict';
const { expect } = require('@playwright/test');
const fs = require('node:fs/promises');
const path = require('node:path');

module.exports = async function verifyNotesResize(page, output, { app } = {}) {
  await fs.mkdir(output, { recursive: true });
  const notes = page.getByRole('textbox', { name: '발표자 노트', exact: true });
  const handle = page.getByRole('separator', { name: '발표자 노트 높이 조절', exact: true });
  await expect(notes).toBeVisible();
  await handle.dblclick();
  const original = await notes.inputValue();
  const content = '발표자 노트를 넓혀 여러 줄의 한글을 확인합니다.\n'.repeat(16);
  await notes.fill(content);
  const before = await page.locator('.canvas-workspace').evaluate(e => e.clientHeight);
  const box = await handle.boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2 - 160, { steps: 12 });
  await page.mouse.up();
  await expect(handle).toHaveAttribute('aria-valuenow', '233');
  await expect(page.locator('.notes-pane')).toHaveCSS('height', '233px');
  expect(await page.locator('.canvas-workspace').evaluate(e => e.clientHeight)).toBeLessThan(before - 140);
  expect(await notes.evaluate(e => e.clientHeight)).toBeGreaterThan(180);
  await expect(notes).toHaveValue(content);
  // Resizing is a view preference, so undo still restores the note edit.
  await page.getByRole('button', { name: '실행 취소', exact: true }).click();
  await expect(notes).toHaveValue(original);
  await page.getByRole('button', { name: '다시 실행', exact: true }).click();
  await expect(notes).toHaveValue(content);
  await expect(page.locator('.save-indicator')).toHaveText('저장됨');
  await page.reload();
  await expect(notes).toHaveValue(content);
  await expect(handle).toHaveAttribute('aria-valuenow', '233');
  await expect(page.locator('.save-indicator')).toHaveText('저장됨');
  await page.screenshot({ path: path.join(output, 'notes-resized.png') });
  await page.getByRole('button', { name: '노트 닫기', exact: true }).click();
  await expect(notes).toHaveCount(0);
  await page.locator('.statusbar').getByRole('button', { name: '노트', exact: true }).click();
  await expect(handle).toHaveAttribute('aria-valuenow', '233');
  await expect(notes).toHaveValue(content);
  await handle.focus();
  await handle.press('ArrowDown');
  await expect(handle).toHaveAttribute('aria-valuenow', '213');
  await handle.press('Shift+ArrowUp');
  await expect(handle).toHaveAttribute('aria-valuenow', '263');
  await handle.dblclick();
  await expect(handle).toHaveAttribute('aria-valuenow', '73');
  await notes.fill(original);
  await handle.focus();
  await expect(page.locator('.save-indicator')).toHaveText('저장됨');
  const report = { ...(app ? { version: await app.evaluate(({ app }) => app.getVersion()), platform: process.platform } : {}), mouseDrag: true, textareaGrows: true, canvasRefits: true, noteUndoUnaffected: true, preferenceAndTextReload: true, closeReopen: true, keyboard: true, doubleClickReset: true };
  await fs.writeFile(path.join(output, 'notes-resize.json'), JSON.stringify(report, null, 2) + '\n');
  console.log('Notes resizing, canvas fit, undo, persistence and reset verified');
  return report;
};
