"""Write/read back a Debian 2.0 archive without a host dpkg installation.

Only a staging directory generated by package-linux.cjs is accepted. All archive
owners are numeric root; only Chromium's shipped sandbox helper is setuid.
"""
import gzip
import hashlib
import io
import json
import pathlib
import sys
import tarfile
import tempfile

payload, output, version = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2]), sys.argv[3]
if not version or any(c not in "0123456789." for c in version):
    raise ValueError("Invalid package version")
files = sorted(p for p in payload.rglob("*") if not p.is_dir())
installed_size = sum(p.lstat().st_size for p in files) // 1024 + 1
control = f"""Package: slide-studio
Version: {version}
Architecture: amd64
Section: editors
Priority: optional
Maintainer: Slide Studio <beaur8-prog@users.noreply.github.com>
Installed-Size: {installed_size}
Depends: libc6 (>= 2.35), libgtk-3-0, libnss3, libnspr4, libx11-6, libxcomposite1, libxdamage1, libxext6, libxfixes3, libxrandr2, libxcb1, libxkbcommon0, libasound2 | libasound2t64, libatk1.0-0, libatk-bridge2.0-0, libatspi2.0-0, libcups2, libdbus-1-3, libdrm2, libgbm1, libexpat1, libglib2.0-0, libpango-1.0-0, libcairo2, libgcc-s1, libstdc++6, xdg-utils, desktop-file-utils, shared-mime-info, fonts-noto-cjk
Homepage: https://github.com/beaur8-prog/slide-studio
Description: Local presentation editor
 Edit PPTX and Slide Studio projects, present slides, and export PPTX or PDF.
 Includes the official Electron runtime; PowerPoint and Node.js are not required.
""".encode()
sandbox = "./opt/slide-studio/chrome-sandbox"

with tempfile.TemporaryDirectory(prefix="slide-studio-deb-") as work:
    work = pathlib.Path(work)
    control_tar, data_tar = work / "control.tar.gz", work / "data.tar.gz"
    with tarfile.open(control_tar, "w:gz", format=tarfile.GNU_FORMAT) as tar:
        info = tarfile.TarInfo("./control")
        info.size, info.mode = len(control), 0o644
        tar.addfile(info, io.BytesIO(control))
        for name in ("postinst", "postrm"):
            content = pathlib.Path(__file__).with_name("linux-" + name).read_bytes()
            info = tarfile.TarInfo("./" + name)
            info.size, info.mode = len(content), 0o755
            tar.addfile(info, io.BytesIO(content))
    def normalize(info):
        info.uid = info.gid = 0
        info.uname = info.gname = "root"
        info.mtime = 0
        info.mode = 0o755 if info.isdir() or info.mode & 0o111 else 0o644
        if info.name == sandbox:
            info.mode = 0o4755
        return info
    with tarfile.open(data_tar, "w:gz", format=tarfile.GNU_FORMAT) as tar:
        for child in sorted(payload.iterdir()):
            tar.add(child, arcname="./" + child.name, filter=normalize)
    # Read back modes, ownership, payload hashes and the sole allowed symlink.
    actual = {}
    with tarfile.open(data_tar) as tar:
        for member in tar:
            assert member.uid == member.gid == 0
            assert member.name.startswith("./") and ".." not in pathlib.PurePosixPath(member.name).parts
            if member.name == sandbox:
                assert member.mode == 0o4755
            else:
                assert not member.mode & 0o6000
            if member.issym():
                assert member.name == "./usr/bin/slide-studio" and member.linkname == "/opt/slide-studio/slide-studio"
            elif member.isfile():
                actual[member.name[2:]] = hashlib.sha256(tar.extractfile(member).read()).hexdigest()
            else:
                assert member.isdir()
    for file in files:
        if not file.is_symlink():
            assert actual[file.relative_to(payload).as_posix()] == hashlib.sha256(file.read_bytes()).hexdigest()
    assert sandbox[2:] in actual
    # Debian's ar archive uses exactly these ordered members (deb(5)).
    with output.open("wb") as out:
        out.write(b"!<arch>\n")
        for name, source in [("debian-binary", io.BytesIO(b"2.0\n")), ("control.tar.gz", control_tar), ("data.tar.gz", data_tar)]:
            size = 4 if isinstance(source, io.BytesIO) else source.stat().st_size
            header = f"{name + '/':<16}{0:<12}{0:<6}{0:<6}{'100644':<8}{size:<10}`\n".encode("ascii")
            assert len(header) == 60
            out.write(header)
            stream = source if isinstance(source, io.BytesIO) else source.open("rb")
            with stream:
                while chunk := stream.read(1024 * 1024):
                    out.write(chunk)
            if size % 2:
                out.write(b"\n")
print(json.dumps({"payloadFiles": len(actual), "installedKiB": installed_size}))
